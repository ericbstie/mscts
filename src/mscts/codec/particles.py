_BLOCK = Schema(block_state=VAR_INT)
_GEYSER = Schema(water_blocks=INT)
_GEYSER_BASE = Schema(water_blocks=INT, burst_impulse_base=FLOAT)
_SPELL = Schema(color=INT, power=FLOAT)
_COLOR = Schema(color=INT)

