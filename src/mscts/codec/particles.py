"""Particles: a VarInt registry id, then that type's options (`ParticleTypes.STREAM_CODEC`).

Pinned with `javap` on the 26.3 server jar: the registration order of `ParticleTypes` gives
the ids (0 to 127), and each type's `streamCodec` its options. 22 types carry options; the
rest carry none. A particle is `{"type": "minecraft:dust", "options": {...}}`, the options
being None for a type that has none. Colors are signed Ints as vanilla writes them (ARGB or
RGB). A block state is its id in the global block state registry, not range checked.
"""

